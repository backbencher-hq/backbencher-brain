// script/m29/generate-wave-doc.ts — M29.R1 (S7): the wave protocol doc,
// GENERATED from the live protocol module. The drift gate is byte-identical
// equality: a hand edit or a protocol change without regeneration fails
// script/m29/verify-wave-protocol.ts.

import { writeFileSync, mkdirSync } from "node:fs"
import path from "node:path"
import { ROOT, WAVE_LANGUAGES, computeCap, type Step } from "./wave-protocol.ts"

const OUT = path.join(ROOT, "docs", "m29", "WAVE-PROTOCOL.md")

const TIER_STEPS: Array<{ id: string; tier: string; name: string; what: string; evidence: string }> = [
  {
    id: "S1", tier: "I0 -> I1", name: "S1-analyzer-conformance",
    what: "the analyzer holds #419 CONFORMANT: every section in the committed SPEC ledger (validation/m14/results/M14.0.SPEC.json) reads pass, mechanically — a language absent from the ledger is declared absent, never assumed",
    evidence: "the SPEC ledger at HEAD (machine-read, not re-run)",
  },
  {
    id: "S2", tier: "I0 -> I1", name: "S2-position-gate",
    what: "the position-mapping gate (script/m24/verify-positions.ts) exits 0 at HEAD — contract §5, the CC1 bug class",
    evidence: "spawned exit code, recorded per run",
  },
  {
    id: "S3", tier: "I0 -> I1", name: "S3-freshness-gate",
    what: "the freshness gate (script/m24/verify-freshness.ts) exits 0 at HEAD — contract §4",
    evidence: "spawned exit code, recorded per run",
  },
  {
    id: "S4", tier: "I0 -> I1", name: "S4-real-index",
    what: "a per-language fixture pack (script/m29/wave-fixtures/<lang>/) is indexed by the REAL compiled indexer (dist/index.js indexProjectParallel) into a real brain.db; an empty index is a fail, a missing pack a blocked reason",
    evidence: "file/symbol/relationship counts from the real index",
  },
  {
    id: "S5", tier: "I1 -> I2", name: "S5-server-leg",
    what: "the real bb_lsp server is driven over stdio against the language's OWN index with per-language feature assertions (hover, definition, references, symbols) — R2's execution leg",
    evidence: "per-language server-leg evidence JSON",
  },
  {
    id: "S6", tier: "I2 -> I3", name: "S6-editor-leg",
    what: "an in-editor run (E5 pattern) exercises the language end to end; the runner honors RECORDED evidence (validation/m29/results/wave-editor-<lang>.json) and never assumes it",
    evidence: "wave-editor-<lang>.json with editor version, OS, commit",
  },
]

const MUTANT_RULES: Array<{ rule: string; caught: string }> = [
  { rule: "a failing SPEC section must drop the cap below I1", caught: "cap stays I0 when S1 fails" },
  { rule: "a language absent from the ledger must be declared absent", caught: "S1 returns conformant=false with the reason" },
  { rule: "a failed component gate must cap below I1", caught: "cap stays I0 when S2/S3 fail" },
  { rule: "a blocked S4 must never read as pass", caught: "cap stays I0; blocker recorded" },
  { rule: "a skipped server leg must cap below I2", caught: "cap stays I1 when S5 is blocked" },
  { rule: "assumed editor evidence must be rejected", caught: "cap stays I2 without recorded S6 evidence" },
]

export function generateWaveDoc(): string {
  const capFor = (steps: Array<[string, Step["status"]]>) =>
    computeCap(steps.map(([step, status]) => ({ step, status, detail: "" })))
  // Worked example: the dry-run baseline a new language starts from.
  const dryRun: Array<[string, Step["status"]]> = [
    ["S1-analyzer-conformance", "pass"],
    ["S2-position-gate", "pass"],
    ["S3-freshness-gate", "pass"],
    ["S4-real-index", "pass"],
    ["S5-server-leg", "blocked"],
    ["S6-editor-leg", "blocked"],
  ]
  const full: Array<[string, Step["status"]]> = [
    ["S1-analyzer-conformance", "pass"],
    ["S2-position-gate", "pass"],
    ["S3-freshness-gate", "pass"],
    ["S4-real-index", "pass"],
    ["S5-server-leg", "pass"],
    ["S6-editor-leg", "pass"],
  ]
  const lines: string[] = []
  lines.push("# The wave protocol — onboarding language N+1 (M29.R1)")
  lines.push("")
  lines.push("Generated by `script/m29/generate-wave-doc.ts` from the live protocol")
  lines.push("module (`script/m29/wave-protocol.ts`). Hand edits fail the drift gate")
  lines.push("(`script/m29/verify-wave-protocol.ts`); regenerate, never hand-edit.")
  lines.push("")
  lines.push("The protocol is the contract §9 extension rule made mechanical: a")
  lines.push("candidate language walks a fixed checklist, and its IDE claim level is")
  lines.push("**capped by what machine evidence proves** — the cap is computed, not")
  lines.push("chosen. Adding language N+1 is a routine gated wave, never a redesign.")
  lines.push("")
  lines.push("## The binding")
  lines.push("")
  lines.push("```")
  lines.push(`I0  default. Unverified. Nothing ships behind a trust label.`)
  lines.push(`I1  protocol-passed   := S1 ^ S2 ^ S3 ^ S4        (cap: ${capFor([["S1-analyzer-conformance", "pass"], ["S2-position-gate", "pass"], ["S3-freshness-gate", "pass"], ["S4-real-index", "pass"]])}-floor rules in code)`)
  lines.push(`I2  index-conformant  := I1 ^ S5                   (worked: ${capFor(dryRun.filter(([s]) => s !== "S6-editor-leg").map(([s, st]) => [s, s === "S5-server-leg" ? "pass" : st] as [string, Step["status"]]))})`)
  lines.push(`I3  editor-verified   := I2 ^ S6                   (worked: ${capFor(full)})`)
  lines.push("```")
  lines.push("")
  lines.push("Any FAILED step caps the language below the tier containing it — a")
  lines.push("failed gate is never climbed past. A BLOCKED step records its machine")
  lines.push("reason in `blockers[]`; silence is guilt (contract §8.3).")
  lines.push("")
  lines.push("## The checklist")
  lines.push("")
  lines.push("| Step | Tier | What it proves | Evidence |")
  lines.push("| --- | --- | --- | --- |")
  for (const s of TIER_STEPS) {
    lines.push(`| ${s.id} \`${s.name}\` | ${s.tier} | ${s.what} | ${s.evidence} |`)
  }
  lines.push("")
  lines.push("## Runner")
  lines.push("")
  lines.push("```bash")
  lines.push("npx tsx script/m29/wave-protocol.ts --language <lang> --out validation/m29/results/wave-<lang>.json")
  lines.push("```")
  lines.push("")
  lines.push(`Registry (${Object.keys(WAVE_LANGUAGES).length} candidates): ${Object.keys(WAVE_LANGUAGES).join(", ")}.`)
  lines.push("Exit 0 = every non-blocked step passed; exit 1 = any real failure; exit")
  lines.push("2 = usage error. The verdict JSON lists every step's status and detail,")
  lines.push("the computed cap, and the blockers.")
  lines.push("")
  lines.push("## Mutation rules (what the verifier must catch)")
  lines.push("")
  for (const m of MUTANT_RULES) {
    lines.push(`- ${m.rule} — ${m.caught}.`)
  }
  lines.push("")
  lines.push("## Fixture packs (R2)")
  lines.push("")
  lines.push("A wave pack lives at `script/m29/wave-fixtures/<lang>/main.<ext>` and is")
  lines.push("authored adversarially: declarations, inheritance, calls, imports,")
  lines.push("cross-file references, and at least one case the language is known to")
  lines.push("get wrong without care (arrays, casts, patterns). The pack is indexed")
  lines.push("for real; the counts land in the verdict. Per-language feature")
  lines.push("assertions (S5) and in-editor evidence (S6) are R2 execution work and")
  lines.push("are honored from recorded evidence only.")
  lines.push("")
  return lines.join("\n")
}

function main(): void {
  mkdirSync(path.dirname(OUT), { recursive: true })
  writeFileSync(OUT, generateWaveDoc())
  console.log(`wrote ${path.relative(ROOT, OUT)}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  main()
}
