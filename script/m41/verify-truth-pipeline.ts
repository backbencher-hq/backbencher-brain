// script/m41/verify-truth-pipeline.ts — M41.T1.
//
// Proves the truth pipeline is honest end to end:
//   1. truth.generated.ts is byte-identical to a fresh generation (--check)
//   2. the generated data contains exactly the artifact tool set (no phantoms,
//      none missing) — the exact lie class the old site shipped
//   3. the committed side-by-side inventory's truth-side verdicts are accurate
//   4. NEGATIVE (spawned, with restore): a drifted truth.generated.ts fails
//      --check; a phantom tool injected into public-tools.json fails generation
//
// Run: npx tsx script/m41/verify-truth-pipeline.ts
// Evidence: validation/m41/results/T1.json

import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync, copyFileSync, rmSync } from "node:fs"
import path from "node:path"

const ROOT = path.resolve(import.meta.dirname ?? ".", "../..")
const RESULTS = path.join(ROOT, "validation/m41/results")
const TRUTH_PATH = path.join(ROOT, "website/src/data/truth.generated.ts")
const TOOLS_JSON_PATH = path.join(ROOT, "docs/data/public-tools.json")
const INVENTORY_PATH = path.join(ROOT, "docs/m41/TRUTH-INVENTORY.md")
const EVIDENCE_PATH = path.join(RESULTS, "T1.json")

let checks = 0
let passed = 0
let negatives = 0

function check(label: string, condition: boolean, detail = ""): void {
  checks++
  if (condition) passed++
  else console.log(`  FAIL: ${label}${detail ? ` — ${detail}` : ""}`)
}
function negative(label: string, condition: boolean, detail = ""): void {
  negatives++
  check(`${label} [negative]`, condition, detail)
}

function runGenerator(args: string[]): { ok: boolean; output: string } {
  try {
    const out = execFileSync("npx", ["tsx", "script/m41/generate-site-truth.ts", ...args], {
      cwd: ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 60_000,
    })
    return { ok: true, output: out }
  } catch (e) {
    const err = e as { stdout?: string; stderr?: string }
    return { ok: false, output: `${err.stdout ?? ""}${err.stderr ?? ""}` }
  }
}

// Extract TRUTH without importing (site tsx config vs repo tsx): regex the
// literal fields the generator emits. The generator is deterministic, so the
// emitted shapes are stable contracts.
function truthField(name: string): string {
  const src = readFileSync(TRUTH_PATH, "utf8")
  const m = src.match(new RegExp(`${name}: "?([^",]+)"?,`))
  return m ? m[1].trim() : ""
}

console.log("M41.T1 truth-pipeline verifier")

// --- 1. generated file exists and is current ---------------------------------

let truthSrc = ""
try {
  truthSrc = readFileSync(TRUTH_PATH, "utf8")
} catch {
  truthSrc = ""
}
check("T1: truth.generated.ts exists", truthSrc.length > 0)
check("T1: generated file declares DO-NOT-EDIT provenance", truthSrc.includes("AUTO-GENERATED by script/m41/generate-site-truth.ts"))

const checkRun = runGenerator(["--check"])
check("T1: --check passes (generated data matches artifacts byte-wise)", checkRun.ok, checkRun.output.split("\n").slice(0, 3).join(" | "))

// --- 2. generated data matches the artifact tool set exactly ------------------

const toolsJson = JSON.parse(readFileSync(TOOLS_JSON_PATH, "utf8")) as { tools: Array<{ name: string; description: string }> }
const artifactNames = toolsJson.tools.map((t) => t.name).sort()

const genToolNames = [...truthSrc.matchAll(/"name": "(bb_[a-z_]+)"/g)].map((m) => m[1]).sort()
check("T1: generated tool list matches public-tools.json exactly", JSON.stringify(genToolNames) === JSON.stringify(artifactNames), `generated=${genToolNames.length} artifact=${artifactNames.length}`)

// The historical lie: phantom tools the old site advertised. None may ever
// reappear in generated truth data.
const PHANTOMS = ["bb_select", "bb_update", "bb_delete", "bb_insert", "bb_write", "bb_refactor", "bb_refresh", "bb_relationships"]
const phantomPresent = PHANTOMS.filter((p) => genToolNames.includes(p))
check("T1: no phantom tool names in generated data", phantomPresent.length === 0, phantomPresent.join(","))

const genVersion = truthField("version") // truthField strips quotes/commas
const pkgVersion = (JSON.parse(readFileSync(path.join(ROOT, "package.json"), "utf8")) as { version: string }).version
check("T1: generated version equals package.json version", genVersion === pkgVersion, `${genVersion} vs ${pkgVersion}`)

const genToolsCount = Number(truthField("tables"))
const schemaSrc = readFileSync(path.join(ROOT, "src/brain/schema-ddl.ts"), "utf8")
const schemaTables = (schemaSrc.match(/CREATE TABLE/g) ?? []).length
check("T1: generated table count equals schema CREATE TABLE count", genToolsCount === schemaTables, `${genToolsCount} vs ${schemaTables}`)

const langMatch = truthSrc.match(/classified: (\d+)/)
const cliMatch = truthSrc.match(/cliCommands: \[(".*")\]/)
check("T1: language count present and > 0", Boolean(langMatch && Number(langMatch[1]) > 0), langMatch?.[1])
check("T1: CLI command list present and non-empty", Boolean(cliMatch && cliMatch[1].length > 2))

// --- 3. inventory truth-side verdicts -----------------------------------------

let inventory = ""
try {
  inventory = readFileSync(INVENTORY_PATH, "utf8")
} catch {
  inventory = ""
}
check("T1: side-by-side inventory committed", inventory.length > 0, INVENTORY_PATH)
check("T1: inventory documents the version lie (A1)", inventory.includes("v1.0.19") && inventory.includes("WRONG"))
check("T1: inventory documents the tool-count lie (A2)", inventory.includes("15 tools") && inventory.includes("11 public MCP tools"))
check("T1: inventory lists all 8 phantom tools", PHANTOMS.every((p) => inventory.includes(`\`${p}\``)))
check("T1: inventory lists the 4 missing real tools", ["bb_analyze", "bb_doc", "bb_edit", "bb_index"].every((t) => inventory.includes(t)))
check("T1: inventory has a resolution map tied to T2", inventory.includes("Resolution map") && inventory.includes("Fixed by"))
// Truth-side consistency: every tool the inventory calls MATCH/real must exist
// in the generated truth; every PHANTOM must not.
const realInInventory = [...inventory.matchAll(/`(bb_[a-z_]+)` \| all real public tools/g)].map((m) => m[1])
check("T1: inventory real-tool verdicts agree with generated truth", realInInventory.every((t) => genToolNames.includes(t)), realInInventory.join(","))

// --- 4. negatives (spawned, with restore) -------------------------------------

// N1: drifted generated file must fail --check.
{
  const backup = path.join(ROOT, "website/src/data/truth.generated.ts.m41bak")
  copyFileSync(TRUTH_PATH, backup)
  try {
    const mutated = readFileSync(TRUTH_PATH, "utf8").replace(/version: "[^"]+"/, 'version: "9.9.9"')
    writeFileSync(TRUTH_PATH, mutated)
    const r = runGenerator(["--check"])
    negative("T1: drifted truth.generated.ts fails --check", !r.ok && r.output.includes("DRIFT"), r.output.split("\n")[0])
  } finally {
    copyFileSync(backup, TRUTH_PATH)
    rmSync(backup)
  }
}

// N2: phantom tool injected into the artifact must fail generation (the
// generator's registry cross-check), not flow into the site data.
{
  const backup = path.join(ROOT, "docs/data/public-tools.json.m41bak")
  copyFileSync(TOOLS_JSON_PATH, backup)
  try {
    const j = JSON.parse(readFileSync(TOOLS_JSON_PATH, "utf8"))
    j.tools.push({ name: "bb_time_travel", description: "phantom tool planted by the T1 negative probe, long enough to pass shape checks" })
    writeFileSync(TOOLS_JSON_PATH, JSON.stringify(j, null, 2) + "\n")
    const r = runGenerator([])
    negative("T1: phantom tool in artifact fails generation", !r.ok && r.output.includes("disagree"), r.output.split("\n").pop()?.trim())
    // and the site data must be untouched by the failed run
    const t = readFileSync(TRUTH_PATH, "utf8")
    negative("T1: failed generation never writes site data", !t.includes("bb_time_travel"))
  } finally {
    copyFileSync(backup, TOOLS_JSON_PATH)
    rmSync(backup)
  }
}

// N3: removing a source artifact fails closed (missing schema), never a
// partial write. Simulated by pointing the generator at a tree without it —
// approximated here by asserting the generator source fail-closes on missing
// files (the spawn-based variant would move real tracked files).
{
  const genSrc = readFileSync(path.join(ROOT, "script/m41/generate-site-truth.ts"), "utf8")
  negative("T1: generator fails closed on missing artifacts", genSrc.includes("source artifact missing/unreadable") && genSrc.includes("process.exit(1)"))
}

// Restore proof: after all mutations, the pipeline must be green again.
const finalCheck = runGenerator(["--check"])
check("T1: pipeline green after all negative probes (restore proven)", finalCheck.ok)

// --- verdict + evidence --------------------------------------------------------

let headCommit = "unknown"
try {
  headCommit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim()
} catch {}

const ok = passed === checks
console.log("")
console.log(`  checks: ${passed}/${checks} passed, ${negatives} negative cases`)
if (!ok) {
  console.log("VERDICT: FAIL")
  process.exit(1)
}
console.log("VERDICT: PASS")

import { mkdirSync } from "node:fs"
mkdirSync(RESULTS, { recursive: true })
const evidence = {
  issue: "M41.T1",
  code: "T1",
  milestone: "M41",
  status: "verified",
  checks,
  passed,
  failed: checks - passed,
  negativeCases: negatives,
  currentCommit: headCommit,
  verifierCommand: "npx tsx script/m41/verify-truth-pipeline.ts",
  evidenceFile: "T1.json",
  generatedAt: new Date().toISOString(),
  truthSummary: {
    version: genVersion,
    tools: genToolNames.length,
    tables: genToolsCount,
    languages: langMatch ? Number(langMatch[1]) : -1,
    cliCommands: cliMatch ? cliMatch[1].split(",").length : -1,
  },
  limitations: [
    "Inventory 'Site claims' column is a T1-baseline snapshot (pre-T2); truth-side verdicts are verified live, claim-side columns are historical by design.",
    "Generator parses SUPPORTED_LANGUAGES structurally; a refactor that renames the map must update generate-site-truth.ts in the same commit (the --check gate will catch divergence immediately).",
    "N3 is a source-level negative (the spawn-based variant would move tracked files); N1/N2 are fully spawned end-to-end.",
  ],
}
writeFileSync(EVIDENCE_PATH, JSON.stringify(evidence, null, 2) + "\n")
console.log(`  evidence: ${path.relative(ROOT, EVIDENCE_PATH)}`)
