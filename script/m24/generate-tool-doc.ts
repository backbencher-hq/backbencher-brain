// script/m24/generate-tool-doc.ts — M24.D1 generator.
//
// Produces docs/m24/TOOL-DOC.md FROM machine evidence + the master plan,
// so the documentation cannot drift from what was verified: the per-language
// claim table, the complement stance, and the limitations are all derived
// from validation/m24/results/*.json and docs/m24/M24-MASTER-PLAN.md.
//
// Run: npx tsx script/m24/generate-tool-doc.ts [--write]
//   (no --write: prints the generated doc to stdout)
//   (--write: writes docs/m24/TOOL-DOC.md)
//
// The drift test in script/m24/verify-docs.ts regenerates and diffs.

import { readFileSync, writeFileSync, existsSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const RESULTS = join(ROOT, "validation", "m24", "results")
const DOC_PATH = join(ROOT, "docs", "m24", "TOOL-DOC.md")
const PLAN = join(ROOT, "docs", "m24", "M24-MASTER-PLAN.md")

/** The launch set — single owner is src/lsp/launch_languages.ts (M29.R2:
 *  the duplicated copy here was a drift hazard; the wave-1 extension flows
 *  through the owner module). */
import { LAUNCH_LANGUAGES } from "../../src/lsp/launch_languages"
import { parseSealedRecord } from "../lib/evidence.ts"

/** Feature -> { evidence file, claim level } mapping, all derived from
 *  machine evidence. A feature is listed only when its evidence says
 *  verified; anything else is declared absent here and can never claim
 *  otherwise (authority: evidence > docs). */
interface FeatureClaim {
  code: string
  evidenceFile: string
  /** Claim level per contract §2: I1 = protocol-passed (V1 gate green). */
  claimLevel: "I1"
}

const FEATURES: FeatureClaim[] = [
  { code: "L2", evidenceFile: "L2.json", claimLevel: "I1" },
  { code: "L3", evidenceFile: "L3.json", claimLevel: "I1" },
  { code: "L4", evidenceFile: "L4.json", claimLevel: "I1" },
  { code: "L5", evidenceFile: "L5.json", claimLevel: "I1" },
]

const FEATURE_NAMES: Record<string, string> = {
  L2: "Hover (signature + usage count + evidence tier + stale marker)",
  L3: "Definition + references",
  L4: "Document + workspace symbols",
  L5: "Call hierarchy (prepare / incoming / outgoing)",
}

function evidenceStatus(code: string): "verified" | "missing" {
  const p = join(RESULTS, `${code}.json`)
  if (!existsSync(p)) return "missing"
  try {
    const d = parseSealedRecord(p) as { status?: string; verdict?: { ok?: boolean } }
    return d.status === "verified" && (d.verdict?.ok ?? true) ? "verified" : "missing"
  } catch {
    return "missing"
  }
}

export function generateToolDoc(): string {
  const plan = readFileSync(PLAN, "utf8")

  // Per-language claim table: every launch language gets the same row because
  // the evidence is language-agnostic at this stage (fixture-backed); the
  // per-language fixture evidence is M25 scope and is declared as such.
  const claimRows = LAUNCH_LANGUAGES.map((lang) => {
    const cells = FEATURES.map((f) => {
      const ok = evidenceStatus(f.code) === "verified"
      return ok ? "I1 ✓" : "—"
    }).join(" | ")
    return `| ${lang} | ${cells} |`
  }).join("\n")

  const featureList = FEATURES.map((f) => {
    const ok = evidenceStatus(f.code) === "verified"
    const status = ok ? "`verified`" : "`missing evidence — not claimed`"
    return `- **${f.code} — ${FEATURE_NAMES[f.code] ?? f.code}**: ${status} (evidence \`validation/m24/results/${f.evidenceFile}\`)`
  }).join("\n")

  return `# bb_lsp — tool documentation (M24)

> Generated by \`script/m24/generate-tool-doc.ts\` from machine evidence.
> Do not edit by hand: regenerate with \`npx tsx script/m24/generate-tool-doc.ts --write\`.
> Drift between this file and the evidence is a failed gate (contract §1).

## What bb_lsp is

A language server that reads the persisted Backbencher index (\`brain.db\`)
and serves hover, definition, references, document and workspace symbols,
and call hierarchy over the Language Server Protocol (LSP 3.18) on stdio.
It is a **complement** to the editor's own analysis, never a replacement:
every response states where its truth comes from (contract §2 claim levels).

## Launch languages

Verified for: ${LAUNCH_LANGUAGES.join(", ")}.
Anything else (Go, Rust, Ruby, … — every language outside the launch set
above) is **declared absent** — the server
replies with an honest not-indexed/not-launch response, never a guess.

## Claim levels (contract §2)

| Language | ${FEATURES.map((f) => f.code).join(" | ")} |
| --- | ${FEATURES.map(() => "---").join(" | ")} |
${claimRows}

- **I1 (protocol-passed)**: the feature passes the reference LSP client
  harness (\`script/m24/lsp_harness.ts\`, wired into \`npm run verify\`) with
  positive and negative cases against a seeded fixture index, and its
  latency meets the contract §3 warm budgets (measured, machine-recorded).
- I3 (editor-verified), I4 (fork-verified), I5 (scoped-verified) are
  **not claimed** — editors and forks are M25 scope, and per contract
  §2 a fork claim is a measured fact, never an assumption.

## Feature status

${featureList}

## What bb_lsp never does (complement stance, contract §7)

- **No completion** — completions are the editor's native surface; the index
  does not pretend to be a compiler.
- **No diagnostics** — the server reports index state, not compile errors.
- **No rename** — cross-file rename requires semantic analysis the index
  does not claim.
- **No fork/editor claims** — nothing here states "works in Cursor/VS Code/…";
  such claims are **not claimed** here and are M25 scope with pinned
  versions and runs.

## Limitations

- Index-sourced only; no compiler-backed types (complement stance).
- Evidence tiers describe relationship-data quality, not symbol truth.
- Per-language *fixture* evidence (one fixture per language) is M25 scope;
  this milestone's fixtures are TypeScript, and the claim table above is the
  language-agnostic protocol-level claim for all five launch languages.
- Latency was measured on the machine recorded in each evidence file;
  cross-platform budgets are M25 scope.
- The bun-source runtime leg of the harness is verified wherever bun is
  installed; in environments without bun it is recorded as \`blocked\` with
  reason — never silently skipped (contract: silence is guilt).

## Budgets (contract §3, warm p95)

| Operation | Budget |
| --- | --- |
| hover / definition / references / document symbols | 50 ms |
| workspace symbols | 150 ms |
| call hierarchy prepare / expand | 100 ms |

Every measurement in \`validation/m24/results/V1.json\` records machine
(kernel, CPU, RAM), repo, commit, and fixture stats.

## Governance

Authority order (lowest may not override higher): executable behavior →
machine evidence + verifier → IDE Honesty Contract + decision record →
this documentation → GitHub issue text. This file cannot upgrade a failed
check into \`verified\` (contract §1; master plan §Authority order).

_Evidence freshness: the G1 gate (\`script/m24/verify-governance.ts\`)
enforces that every claim above traces to evidence that is fresh at the
current commit — regenerated, not grandfathered._
`
}

// Self-execution: --write persists, otherwise print to stdout.
if (process.argv[1]?.endsWith("generate-tool-doc.ts")) {
  const doc = generateToolDoc()
  if (process.argv.includes("--write")) {
    writeFileSync(DOC_PATH, doc)
    console.log(`wrote ${DOC_PATH} (${doc.split("\n").length} lines)`)
  } else {
    process.stdout.write(doc)
  }
}
