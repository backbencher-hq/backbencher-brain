/**
 * The SCSS completeness spec generator.
 *
 *   bun script/m14/tmp/scss-spec-generate.ts
 *
 * Every cell in the output is derived from a MEASUREMENT or an ADJUDICATION recorded
 * here, and the two are never mixed: a type is only `handled_verified` if the analyzer
 * demonstrably reaches it AND it was observed doing something, and a type the corpus
 * never produces is `internal_silent` with the reason it is silent rather than being
 * quietly dropped.
 *
 * WHY A SPEC AND NOT JUST A CENSUS. F8 (the census) reports which node types a corpus
 * produces. That is a fact about the corpus. This is a fact about the LANE: which of
 * those types reach an entity, which produce nothing a Sass author would expect, and
 * which were never seen at all. The gap between those two is the defect class a census
 * cannot see, because a census only looks at what the corpus happens to contain.
 *
 * THE THREE BUCKETS, and why the middle one is the honest one
 *
 *   handled_verified   reachable AND observed doing something, in the corpus or in a
 *                      reproduction when the corpus has none
 *   internal_silent    the type is a wrapper, a hidden rule, a punctuation token, or a
 *                      construct the corpus never exercises. Recorded with WHICH of
 *                      those it is — "no corpus occurrence" is a fact, and it is not
 *                      the same fact as "handled"
 *   gap                parses CLEAN and still produces nothing a Sass author would
 *                      expect. An empty list is a claim with a method.
 *
 * The SCSS grammar is a SUPERSET of the CSS one, so most of its vocabulary is already
 * adjudicated by `script/m14/spec/css-completeness.json`. This spec does not restate
 * those — it covers the SCSS-SPECIFIC types and records the inheritance explicitly,
 * because a spec that duplicated 60 CSS rulings would rot the moment either grammar
 * moved and nobody would notice which half had gone stale.
 */

import { readFileSync, writeFileSync, mkdirSync } from "fs"
