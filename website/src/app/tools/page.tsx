import Link from 'next/link'
import { BRAIN_TOOLS } from '@/data/brain-tools'
import { AtlasPage, PageHead } from '@/components/atlas/AtlasPage'
import { CONSOLE_CSS } from '@/components/tools/console-css'
import { TOOLS_ATLAS_CSS } from '@/components/tools/atlas-css'
import { ToolConsoleSync } from '@/components/tools/ToolConsoleSync'
import { ToolPanel } from '@/components/tools/ToolPanel'
import { ToolRail } from '@/components/tools/ToolRail'
import { formatWords, SPREAD, SPREAD_RATIO, TOTAL_RECORD_WORDS } from '@/components/tools/record'

// M41.D1 / M56.T1 — the agent tool reference, a two-pane console on paper:
//
//   left  · an index of every public tool (display-grouped, each row naming the
//           tool's job and carrying a meter of how much contract it commits to)
//   right · the selected tool's contract, ordered by what a reader is deciding
//           (see ToolPanel.tsx), with the declared limits at its centre.
//
// This page is a register, not a pitch. It does not argue for the product, and
// it deliberately shares no sentence with the homepage: the homepage orients,
// this page is where a reader who has picked a tool finds out what it commits
// to and what it refuses. The one thing this page says that no other page says
// is the spread — the sixteen entries are not the same size, and that spread is
// measured here from the generated data rather than asserted.
//
// 2026-11-07 — Evidence Atlas surface. The console interaction is unchanged
// (plain HTML radios, a CSS :has() rule, no client JavaScript required), but the
// surface is now paper: AtlasPage chrome, a serif title block, a hairline rail,
// and a reading column instead of a dark card stack. The stylesheet lives in
// ./atlas-css.ts so the generated selection rules and the static paint share one
// token set. `console-index` stays declared here, where the design gate reads it.
//
// Selection is plain HTML radio buttons driven by a CSS :has() rule — no client
// JavaScript is required, no framer-motion, no opacity traps. Every tool's full
// reference is server-rendered in the static HTML; clicking an index row only
// flips which panel is visible.
//
// Deep links: every panel carries its tool name as an anchor id, so /tools#bb_impact
// is a real URL. The stylesheet makes a targeted panel visible on its own, and
// ToolConsoleSync binds the fragment to the radio set and writes the selected
// tool back into the address bar — enhancement only, guarded, and the console is
// complete without it.
//
// M56.T1: every tool fact rendered below comes from
// website/src/data/tools.generated.ts (generated by `bun run docs:generate` from
// the executable registry and docs/tools/*.md). This page hand-types no tool
// facts, and no word count in it is a literal — verify-tools-truth.ts fails the
// build if that changes.

export default function ToolsPage() {
  return (
    <AtlasPage>
      <style dangerouslySetInnerHTML={{ __html: `${CONSOLE_CSS}\n${TOOLS_ATLAS_CSS}` }} />
      <div className="container">
        <PageHead
          title={
            <>
              Every tool, and what it <i>refuses.</i>
            </>
          }
          lead={
            <>
              Every entry is the tool&rsquo;s own registry record, rendered whole: what it returns, the bounds it
              declares, and the limits its reference page records &mdash; including the measurements that caught it
              answering wrongly. Nothing here is written to make a tool look capable.
            </>
          }
          meta={
            <>
              {BRAIN_TOOLS.length} MCP tools · {formatWords(TOTAL_RECORD_WORDS)} words of generated contract ·{' '}
              {SPREAD_RATIO.toFixed(1)}× between the largest entry ({SPREAD.largest.name}) and the smallest (
              {SPREAD.smallest.name})
            </>
          }
        />

        <div className="reading" style={{ paddingBottom: 0 }}>
          <p>
            Bar length in the index is that word count &mdash; how much a tool commits to before you spend a call on
            it. It measures the record; it does not rate the tool.
          </p>
          <p>
            Every tool has its own address, so a reference to one is a link rather than an instruction:{' '}
            <code>/tools#bb_impact</code>.
          </p>
        </div>

        <div className="tools-shell">
          <ToolRail className="console-index" />

          {/* Reference panels — all sixteen in the static HTML, one visible. */}
          <div>
            {BRAIN_TOOLS.map((tool) => (
              <ToolPanel key={tool.name} tool={tool} />
            ))}
          </div>
        </div>

        <div className="tools-foot">
          <p>
            Every entry above is generated from the same tool manifest the MCP server and the CLI expose, and from the
            shipped reference pages under <code>docs/tools/</code>. Where a tool behaves differently from what is
            written here, that is a bug worth reporting rather than a documentation nit.
          </p>
          <div className="tools-doors">
            <Link className="btn-ghost" href="/docs#agent-tools">
              Agent tools in the guide <span aria-hidden>→</span>
            </Link>
            <p className="mono-note">
              Wiring the server: <code>bb mcp</code>
            </p>
          </div>
        </div>
      </div>
      <ToolConsoleSync />
    </AtlasPage>
  )
}
