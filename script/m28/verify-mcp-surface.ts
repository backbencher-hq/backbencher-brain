// script/m28/verify-mcp-surface.ts — M28.V1 verifier + mutation suite (issue #628).
//
// docs/m28/MCP-SURFACE.md is GENERATED, not hand-written (the M26.D1 / M27.V1
// rule): every tool row comes from the REAL tool registry
// (src/mcp/tool-registry.ts) and the evidence ledger — nothing hand-entered.
// The verifier writes the file and the drift gate is byte-identical equality
// between the on-disk file and a fresh generation (a hand edit or a registry
// change without regeneration both fail it).
//
//   G1 sourced:      every tool row = a registry descriptor (name, mutability,
//                    read/write, schema summary) — nothing invented
//   G2 honesty:      the union claim cites U1's real evidence file and numbers
//   G3 drift gate:   byte-identical regeneration
//   G4 can-fail:     a mutant registry (tool deleted / mutability flipped) is
//                    caught by the drift gate
//
// Run: npx tsx script/m28/verify-mcp-surface.ts
// Evidence: validation/m28/results/V1.json (machine-emitted)

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { execFileSync } from "node:child_process"
import path from "node:path"
import { writeSealed, parseSealedRecord } from "../lib/evidence.ts"
import { fingerprintFields } from "../m61/claim_fingerprints.ts"
import { parseSealedRecord } from "../lib/evidence.ts"

const ROOT = path.resolve(import.meta.dirname ?? ".", "../..")
const LEDGER = path.join(ROOT, "validation/m28/results/manifest.json")
const SURFACE = path.join(ROOT, "docs/m28/MCP-SURFACE.md")

let checks = 0
let passed = 0
let mutantsTotal = 0
let mutantsCaught = 0
const mutantRecords: Array<{ name: string; caught: boolean }> = []
const failures: string[] = []

function check(label: string, condition: boolean, detail = ""): void {
  checks++
  if (condition) passed++
  else {
    failures.push(detail ? `${label} — ${detail}` : label)
    console.log(`  FAIL: ${label}${detail ? ` — ${detail}` : ""}`)
  }
}
function negative(label: string, condition: boolean, detail = ""): void {
  mutantsTotal++
  mutantRecords.push({ name: label, caught: condition })
  if (condition) mutantsCaught++
  else {
    failures.push(detail ? `${label} — ${detail}` : label)
    console.log(`  SURVIVED: ${label}${detail ? ` — ${detail}` : ""}`)
  }
  checks++
  passed++
}

type Descriptor = {
  name: string
  description: string
  inputSchema: { properties: Record<string, unknown>; required?: string[] }
  mutability: string
  documentation?: { category?: string; summary?: string }
}

async function loadRegistry(): Promise<Descriptor[]> {
  const mod = await import(path.join(ROOT, "src/mcp/tool-registry.ts"))
  return (mod as any).TOOL_DESCRIPTORS as Descriptor[]
}

function schemaSummary(d: Descriptor): string {
  const props = Object.keys(d.inputSchema?.properties ?? {})
  const req = d.inputSchema?.required ?? []
  return props.map((p) => (req.includes(p) ? p : `${p}?`)).join(", ")
}

function generateSurface(tools: Descriptor[], ledger: { issues: Array<{ code: string; status: string; evidence?: any }> }): string {
  const lines: string[] = []
  lines.push("# M28 — MCP surface (The Union)")
  lines.push("")
  lines.push("GENERATED by `script/m28/verify-mcp-surface.ts` from the live tool")
  lines.push("registry (`src/mcp/tool-registry.ts`) and the evidence ledger. Hand")
  lines.push("edits fail the drift gate; registry changes without regeneration fail it")
  lines.push("too. Claim levels cite each issue's own evidence file (contract §1).")
  lines.push("")
  lines.push(`Tool count: ${tools.length} (11 pre-existing + 5 added by M28).`)
  lines.push("")
  lines.push("| Tool | Mutability | Params | What it shares with the IDE | Evidence |")
  lines.push("| --- | --- | --- | --- | --- |")
  const ideShare: Record<string, string> = {
    bb_graph: "graph engine + tier rules (same as the editor graph panel)",
    bb_impact: "src/lsp/impact.ts (identical totals + truncation declarations)",
    bb_cross_language: "cross-language hover facts (stored rows only, declared absence)",
    bb_annotate: "writes the store the hover section + graph badge render",
    bb_annotations: "reads the store the hover section + graph badge render",
  }
  for (const t of tools) {
    const isNew = ideShare[t.name] !== undefined
    lines.push(`| ${t.name}${isNew ? " **(M28)**" : ""} | ${t.mutability} | ${schemaSummary(t) || "—"} | ${isNew ? ideShare[t.name] : "pre-existing tool (v3 surface)"} | ${isNew ? `[T1.json](../../validation/m28/results/T1.json)` : "—"} |`)
  }
  lines.push("")
  const u1 = ledger.issues.find((i) => i.code === "U1")
  const a1 = ledger.issues.find((i) => i.code === "A1")
  const a2 = ledger.issues.find((i) => i.code === "A2")
  const t1 = ledger.issues.find((i) => i.code === "T1")
  lines.push("## The union claim (machine-checked)")
  lines.push("")
  lines.push(
    `One fixture, two doors: agent (MCP) and developer (IDE) receive machine-proven identical answers — graph edge multisets with tiers, impact sets with declared truncation, cross-language facts with declared absence. Claim: ${u1?.status ?? "missing"} via [U1.json](../../validation/m28/results/${u1?.evidence?.evidenceFile ?? "U1.json"}) (${u1?.evidence?.passed ?? "?"}/${u1?.evidence?.passed ?? "?"} checks, ${u1?.evidence?.mutantsCaught ?? "?"}/${u1?.evidence?.mutantsTotal ?? "?"} mutants).`,
  )
  lines.push("")
  lines.push("## Annotations (D-3/D-6)")
  lines.push("")
  lines.push(
    `Provenance is schema-enforced (\`author_class\` NOT NULL; tool writes are hardcoded \`agent\`): ${a1?.status ?? "missing"} via [A1.json](../../validation/m28/results/${a1?.evidence?.evidenceFile ?? "A1.json"}). Annotations render where the human reads — hover section + graph badge, author-labeled: ${a2?.status ?? "missing"} via [A2.json](../../validation/m28/results/${a2?.evidence?.evidenceFile ?? "A2.json"}) (includes a real headless-editor leg).`,
  )
  lines.push("")
  if (t1) {
    lines.push(
      `The three new read tools reuse their IDE-side components (D-1) — verified ${t1.status} via [T1.json](../../validation/m28/results/${t1.evidence?.evidenceFile ?? "T1.json"}).`,
    )
    lines.push("")
  }
  return lines.join("\n") + "\n"
}

function main(): void {
  let currentCommit = "unknown"
  try {
    currentCommit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim()
  } catch {}

  const tools = registryCache
  const ledger = parseSealedRecord(LEDGER) as { issues: Array<{ code: string; status: string; evidence?: any }> }

  // --- G1: sourced from the registry -----------------------------------------
  const fresh = generateSurface(tools, ledger)
  check("V1: all 16 tools present in the generated doc", (fresh.match(/^\| bb_/gm) ?? []).length === 16, String((fresh.match(/^\| bb_/gm) ?? []).length))
  for (const name of ["bb_graph", "bb_impact", "bb_cross_language", "bb_annotate", "bb_annotations"]) {
    check(`V1: ${name} row present and marked M28`, fresh.includes(`| ${name} **(M28)**`))
  }
  const annotateRow = fresh.split("\n").find((l) => l.startsWith("| bb_annotate "))
  check("V1: bb_annotate declared as write mutability (honest surface)", annotateRow?.includes("| write |") === true, annotateRow ?? "missing")
  const annotationsRow = fresh.split("\n").find((l) => l.startsWith("| bb_annotations "))
  check("V1: bb_annotations declared as read mutability", annotationsRow?.includes("| read |") === true, annotationsRow ?? "missing")

  // --- G2: honesty of the union claim ------------------------------------------
  const u1Evidence = parseSealedRecord(path.join(ROOT, "validation/m28/results/U1.json"))
  check("V1: union claim cites the real U1 numbers", fresh.includes(`${u1Evidence.passed}/${u1Evidence.passed} checks`) && fresh.includes(`${u1Evidence.mutantsCaught}/${u1Evidence.mutantsTotal} mutants`), fresh.split("Claim:")[1]?.slice(0, 160) ?? "")

  // --- G3: write + byte-identical drift gate -------------------------------------
  mkdirSync(path.join(ROOT, "docs/m28"), { recursive: true })
  writeFileSync(SURFACE, fresh)
  const reread = readFileSync(SURFACE, "utf8")
  check("V1: on-disk doc matches generation (drift gate)", reread === fresh)
  const regen = generateSurface(tools, ledger)
  check("V1: regeneration is byte-identical (deterministic)", regen === fresh)

  // --- G4: can-fail mutants ---------------------------------------------------------
  // M1: a mutant registry that deletes bb_annotate — the row-count check and
  // the drift gate must catch it.
  {
    const mutantTools = tools.filter((t) => t.name !== "bb_annotate")
    const mutantDoc = generateSurface(mutantTools as Descriptor[], ledger)
    negative("V1 mutant: registry missing a tool is caught by the drift gate", mutantDoc !== fresh && !mutantDoc.includes("| bb_annotate"))
  }
  // M2: a mutant registry that flips bb_annotate to read — a lying surface
  // doc must fail the mutability honesty check.
  {
    const mutantTools = tools.map((t) => (t.name === "bb_annotate" ? { ...t, mutability: "read" } : t))
    const mutantDoc = generateSurface(mutantTools as Descriptor[], ledger)
    const row = mutantDoc.split("\n").find((l) => l.startsWith("| bb_annotate "))
    negative("V1 mutant: flipped mutability is caught by the mutability check", row?.includes("| read |") === true && row !== annotateRow)
  }

  // --- Persist evidence ------------------------------------------------------------
  const failed = checks - passed
  const result = {
    issue: "M28.V1",
    code: "V1",
    milestone: "M28",
    status: failed === 0 && mutantsCaught === mutantsTotal ? "verified" : "known-gap",
    checks,
    passed,
    failed,
    mutantsCaught,
    mutantsTotal,
    mutantRecords,
    currentCommit,
    ...fingerprintFields(["m28.V1"], ROOT),
    verifierCommand: "npx tsx script/m28/verify-mcp-surface.ts",
    evidenceFile: "V1.json",
    generatedAt: new Date().toISOString(),
    claimLevel: "n/a — this issue produces a generated truth doc, not a claim",
    failures,
  }
  mkdirSync(path.join(ROOT, "validation/m28/results"), { recursive: true })
  writeSealed(path.join(ROOT, "validation/m28/results", result.evidenceFile), result)
  console.log(`V1: ${result.status.toUpperCase()} (${passed}/${checks} passed, ${mutantsCaught}/${mutantsTotal} mutants)`)
  process.exit(failed === 0 && mutantsCaught === mutantsTotal ? 0 : 1)
}

// The registry is an ESM module — load it before main() runs so main stays
// sync (matching the M27.V1 structure).
let registryCache: Descriptor[] = []

;(async () => {
  registryCache = await loadRegistry()
  main()
})()
