// ── 1. the vocabulary the WIRED grammar can produce ───────────────────────────
// Enumerated from the loaded wasm rather than from a checked-in list, so a grammar
// patch that adds a type cannot be invisible here. `node-types.json` is generated and
// therefore untracked; the wasm is the thing the product loads.
await TSParser.init()
const parser = new TSParser()
parser.setLanguage(await Language.load("wasm/tree-sitter-scss.wasm"))

// `node-types.json` is GENERATED by `tree-sitter generate` from the vendored
// grammar.js and is deliberately untracked (it is a build output, like parser.c).
// It is read rather than checked in for the same reason parser.c is not: a checked-in
// copy is a second statement of the grammar that can disagree with the one the wasm was
// built from. The pin's source<->wasm check is what makes it trustworthy — it proves
// the wired bytes ARE a build of this grammar.js, so this file describes the wasm.
//
// The first version read `(lang as any).types`, which this web-tree-sitter build does
// not expose: it returned undefined and the spec came out with 0 named types and 2
// "declared" ones, which is a spec that agrees with nothing.
const nodeTypes: { type: string; named: boolean }[] = JSON.parse(
  readFileSync("grammars/tree-sitter-scss/src/node-types.json", "utf8"),
)

// ── 2. what the CORPUS actually produces ──────────────────────────────────────
// Measured, not assumed. A type with no corpus occurrence is labelled as such in the
// spec, which is the difference between "handled" and "never looked at".
const ROOT = "/home/ishaq2321/bb_tests/repositories"
const CORPORA = ["element-plus", "phpmyadmin", "vue-core", "vue-element-admin"]

const { readdirSync, statSync } = await import("fs")
const { join } = await import("path")
function walk(dir: string, out: string[], depth = 0): Promise<void> | void {
  if (depth > 14) return
  let entries: string[]
  try {
    entries = readdirSync(dir)
  } catch {
    return
  }
  for (const e of entries) {
    if (["node_modules", ".git", "target", "vendor", "dist", "build"].includes(e)) continue
    const p = join(dir, e)
    let st
    try {
      st = statSync(p)
    } catch {
      continue
    }
    if (st.isDirectory()) walk(p, out, depth + 1)
    else if (e.endsWith(".scss") && st.size > 0) out.push(p)
  }
}
const files: string[] = []
for (const r of CORPORA) walk(join(ROOT, r), files)
files.sort()

const corpusTypes = new Set<string>()
let filesParsed = 0
for (const f of files.slice(0, 200)) {
  let tree
  try {
    tree = parser.parse(readFileSync(f, "utf8"))
  } catch {
    continue
  }
  filesParsed++
  ;(function w(n: any) {
    if (n.isNamed && n.type && !n.type.startsWith("_")) corpusTypes.add(n.type)
    for (const c of n.children ?? []) w(c)
  })(tree.rootNode)
}

// ── 3. what the ANALYZER can reach ────────────────────────────────────────────
// Two independent readings, so a type the analyzer NAMES and a type it only walks
// past are not conflated. The census vocabulary is not the analyzer's vocabulary.
// The CSS spec, so the ~60 types this lane INHERITS are RESOLVED against it rather
// than left unadjudicated or restated. Reading it is what turns "most likely reached
// by the delegated walk" into a claim with a source: a type the CSS spec adjudicates
// has a ruling, and the SCSS lane reaches it through the same walk.
let cssRulings: Set<string> | null = null
try {
  const css = JSON.parse(readFileSync("script/m14/spec/css-completeness.json", "utf8"))
  cssRulings = new Set<string>()
  // The CSS spec stores `types` as a LIST of names, and `gap` as `gaps`. The first
  // version walked them as objects, so `Object.keys` on an array gave indices
  // ("0","1","2") and NOTHING matched — which is why all 60 inherited cells stayed
  // unadjudicated while the loader reported success. A loader that reads a different
  // shape than it expects and finds nothing is worse than one that throws.
  for (const bucket of ["handled_verified", "internal_silent"]) {
    const t = css?.[bucket]?.types
    if (Array.isArray(t)) for (const k of t) cssRulings.add(String(k))
  }
  const g = css?.gap?.gaps
  if (Array.isArray(g)) for (const k of g) cssRulings.add(String(k))
  // the CSS spec also records types resolved THROUGH a parent construct
  const viaParent = css?.handled_verified?.resolved_via_parent
  if (viaParent && typeof viaParent === "object") for (const k of Object.keys(viaParent)) cssRulings.add(k)
} catch {
  cssRulings = null
}

const analyzerSrc = readFileSync("src/ast/real-scss-analyzer.ts", "utf8")
const namedByAnalyzer = new Set<string>()
for (const m of analyzerSrc.matchAll(/type\s*===\s*"([a-z_]+)"/g)) namedByAnalyzer.add(m[1]!)
for (const m of analyzerSrc.matchAll(/type\s*!==\s*"([a-z_]+)"/g)) namedByAnalyzer.add(m[1]!)
for (const m of analyzerSrc.matchAll(/childForFieldName\("([a-z_]+)"\)/g)) namedByAnalyzer.add(m[1]!)

