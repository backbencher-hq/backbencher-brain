const NOTE_ADDENDUM =
  " AMENDED 2026-09-24 (#933, the dart half): this audit predated three waves that landed on the analyzer — the DT2 `uses` surface (interpolation, parameter/local/lambda, and selector member reads), `overrides` derived through an IMPLEMENTED interface, and `instantiates` for a CONST constructor invocation. Its old parenthetical said `overrides via extends-base only`; that was the audit's own scope, not the contract. Every one of the 32 false positives the live verifier reported was read back against the fixture SOURCE TEXT (each fact's evidence reference quotes the line) and every one is a correct edge, so the analyzer was not changed for them: the truth was stale. The 5 remaining facts are the analyzer's sub-threshold refusals (bare member reads at confidence 0.6), pinned as expectedState=unknown so that a wave which stops emitting them fails as missingClassifications rather than passing silently. Totals: 119 -> 156 facts."

function main() {
  const doc = JSON.parse(fs.readFileSync(P, "utf8"))
  const key = (f: any) => [f.layer, f.kind, f.file ?? "", f.line ?? "", f.sourceId ?? "", f.targetId ?? "", JSON.stringify({ type: f.attributes?.type })].join("|")
  const existing = new Set(doc.facts.map(key))

  const added: any[] = []
  for (const a of ADDED) {
    const m = /^rel:([^:]+):([^:]+):([^:]+):(.+)$/.exec(a.id)
    if (!m) throw new Error(`bad id: ${a.id}`)
    const [, file, type, sourceId, targetId] = m
    const fact: any = {
      id: a.id,
      layer: "relationships",
      kind: "relationship",
      file,
      sourceId,
      targetId,
      attributes: { type },
      evidence: { authority: "manual_audit", reference: a.reference },
    }
    if (a.expectedState) fact.expectedState = a.expectedState
    const k = key(fact)
    if (existing.has(k)) throw new Error(`duplicate comparison key (already in truth): ${a.id}`)
    existing.add(k)
    added.push(fact)
  }

  doc.source = doc.source.replace(/\s*$/, "") .replace(/\.\s*AMENDED.*$/s, ".") + NOTE_ADDENDUM
  doc.facts = [...doc.facts, ...added]
  fs.writeFileSync(P, JSON.stringify(doc, null, 1) + "\n")
  console.log(`amended ${P}: +${added.length} facts (${ADDED.filter((a) => a.expectedState).length} expected-unknown) — total ${doc.facts.length}`)
}

main()
